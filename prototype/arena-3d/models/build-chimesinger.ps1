# Rebuilds models/chimesinger.glb (WebP, browser) and the Unity copy (JPEG) from the Meshy sources with Blender, runs the
# mesh-level QA (staff/body overlap on every frame, grip distances, staff rigidity), then wraps the browser GLB in
# chimesinger-glb.js so pages opened from disk (file://) can load it.
#   powershell -File build-chimesinger.ps1 -RunRef <Soldier.glb> [-Out <dir>] [-Unity <out .glb>] [-Source <meshy body .glb>] [-Staff <meshy staff .glb>]
# -Out defaults to this folder; point it (and -Unity) at a scratch folder to try a build without touching the project.
# Pass -Unity '' to skip the Unity copy. The grip solve is cached in the work folder (it takes a few minutes).
param(
  [string]$Source = '',
  [string]$Staff = '',
  [string]$Blender = 'C:\Program Files\Blender Foundation\Blender 5.2\blender.exe',
  # Mixamo-skeleton GLB whose 'Run' clip drives Run/Sprint (three.js examples/models/gltf/Soldier.glb). Not committed.
  [Parameter(Mandatory = $true)][string]$RunRef,
  [string]$Out = '',
  [string]$Unity = 'default'
)
$ErrorActionPreference = 'Stop'
# defaults are filled here: Windows PowerShell 5.1 leaves $PSScriptRoot empty inside the param block
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $Source) { $Source = (Get-ChildItem (Join-Path $here 'upload\Meshy') -Filter '*Chimesinger_1*texture.glb' | Select-Object -First 1).FullName }
if (-not $Staff) { $Staff = (Get-ChildItem (Join-Path $here 'upload\Meshy') -Filter '*Chimesinger_Staff*texture.glb' | Select-Object -First 1).FullName }
if (-not $Out) { $Out = $here }
if ($Unity -eq 'default') { $Unity = Join-Path $here '..\..\..\unity\Assets\LastBell\Characters\Chimesinger\Resources\Characters\Chimesinger.glb' }
$work = Join-Path $env:TEMP 'lastbell-chimesinger-build'; New-Item -ItemType Directory -Force $work | Out-Null
New-Item -ItemType Directory -Force $Out | Out-Null
$glb = Join-Path $Out 'chimesinger.glb'
if ($Unity) { New-Item -ItemType Directory -Force (Split-Path $Unity) | Out-Null }
& $Blender -b -P (Join-Path $here 'blender\chimesinger_prep.py') -- $Source $work 50000 $Staff | Select-String '^(TRIS|STAFF_TRIS|GLOW)|Error|Traceback'
& $Blender -b (Join-Path $work 'chimesinger_prep.blend') -P (Join-Path $here 'blender\chimesinger_rig.py') -- $work $glb $RunRef $Unity | Select-String '^(HAND|SHAFT|GRIP|STANCE|UNWEIGHTED|MOCAP|EXPORTED)|Error|Traceback'
& $Blender -b (Join-Path $work 'chimesinger_rig.blend') -P (Join-Path $here 'blender\chimesinger_qa.py') -- (Join-Path $work 'chimesinger_qa.json') | Select-String '^QA|Error|Traceback'
$b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($glb))
Set-Content (Join-Path $Out 'chimesinger-glb.js') "// Generated by build-chimesinger.ps1 from chimesinger.glb. Do not edit.`nwindow.CHIMESINGER_GLB_B64 = '$b64';" -NoNewline -Encoding ascii
"wrote $glb, chimesinger-glb.js" + $(if ($Unity) { " and $Unity" } else { '' })
